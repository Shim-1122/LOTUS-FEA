"""Optional ABAQUS/Standard input generation (and execution only when a
licensed ``abaqus`` command is found on PATH).

Generated decks are labelled UNEXECUTED until an ABAQUS job has actually run;
their existence is never evidence that ABAQUS was run.  Parameter conversions
from FEBio conventions are explicit:

* HGO:  C10 = c/2,  D = 2/k,  k1, k2, kappa unchanged (ABAQUS *ANISOTROPIC
  HYPERELASTIC, HOLZAPFEL, LOCAL DIRECTIONS=2), fibre directions written as
  local directions at +/-gamma from e1 per element (*DISTRIBUTION).
* Ogden (FEBio c_i/m_i^2 convention):  ABAQUS 2 mu_i/alpha_i^2 = c_i/m_i^2
  -> mu_i = c_i/2, alpha_i = m_i.
* Mooney-Rivlin: C10 = c1, C01 = c2.
* Volumetric terms DIFFER: ABAQUS polynomial/Ogden use sum (1/D_i)(J-1)^{2i};
  FEBio uses k/2 (ln J)^2.  D1 = 2/k matches the initial bulk modulus only.
  This is a known model difference and is written into the deck header.
"""
from __future__ import annotations

import os
import shutil
import subprocess

import numpy as np

from ..mesh.model import FEModel

ELTYPE = {"tet4": "C3D4H", "penta6": "C3D6H", "hex8": "C3D8H"}


def write_inp(path: str, model: FEModel, spec, title: str = "rlfea") -> dict:
    L = ["*HEADING", f"{title} -- generated by rlfea; UNEXECUTED unless an accompanying ABAQUS .odb/.sta exists; units mm-N-MPa",
         "** Volumetric energy differs from FEBio (ABAQUS (J-1)^2 vs FEBio (ln J)^2 for Ogden/Mooney-Rivlin); D1 = 2/k.",
         "*NODE"]
    for i, x in enumerate(model.nodes):
        L.append(f"{i + 1}, {x[0]:.9g}, {x[1]:.9g}, {x[2]:.9g}")
    eid = 0
    for b in model.blocks:
        L.append(f"*ELEMENT, TYPE={ELTYPE[b.etype]}, ELSET={b.name}")
        for c in b.conn:
            eid += 1
            L.append(f"{eid}, " + ", ".join(str(int(n) + 1) for n in c))
    for name, ns in model.nodesets.items():
        L.append(f"*NSET, NSET={name}")
        L += [", ".join(str(int(n) + 1) for n in ns[i:i + 16]) for i in range(0, len(ns), 16)]
    mats_written = set()
    off = 0
    rigid_refs = {}
    for b in model.blocks:
        mname = spec.block_material[b.name]
        m = spec.materials[mname]
        if m.get("rigid"):
            ref = len(model.nodes) + 1 + len(rigid_refs)
            rigid_refs[mname] = ref
            L.append(f"*NODE\n{ref}, " + ", ".join(f"{v:.9g}" for v in m["com"]))
            L.append(f"*NSET, NSET=RP_{mname}\n{ref}")
            L.append(f"*RIGID BODY, ELSET={b.name}, REF NODE={ref}")
            off += len(b.conn)
            continue
        if m["febio_type"] == "Holzapfel-Gasser-Ogden" and b.mat_axis is not None:
            L.append(f"*DISTRIBUTION, NAME=ori_{b.name}, LOCATION=ELEMENT, TABLE=ori_tab")
            L.append(", 1., 0., 0., 0., 1., 0.")
            for i, (a, d) in enumerate(b.mat_axis):
                L.append(f"{off + i + 1}, {a[0]:.6g}, {a[1]:.6g}, {a[2]:.6g}, {d[0]:.6g}, {d[1]:.6g}, {d[2]:.6g}")
            L.append(f"*ORIENTATION, NAME=ori_{b.name}, LOCAL DIRECTIONS=2\nori_{b.name}")
            g = np.deg2rad(m["params"]["gamma"])
            L.append(f"{np.cos(g):.8f}, {np.sin(g):.8f}, 0.\n{np.cos(g):.8f}, {-np.sin(g):.8f}, 0.")
            L.append(f"*SOLID SECTION, ELSET={b.name}, MATERIAL={mname}, ORIENTATION=ori_{b.name}")
        else:
            L.append(f"*SOLID SECTION, ELSET={b.name}, MATERIAL={mname}")
        off += len(b.conn)
        if mname in mats_written:
            continue
        mats_written.add(mname)
        p = m["params"]
        L.append(f"*MATERIAL, NAME={mname}")
        t = m["febio_type"]
        if t == "Holzapfel-Gasser-Ogden":
            L.append("*ANISOTROPIC HYPERELASTIC, HOLZAPFEL, LOCAL DIRECTIONS=2")
            L.append(f"{p['c'] / 2:.8g}, {2.0 / p['k']:.8g}, {p['k1']:.8g}, {p['k2']:.8g}, {p['kappa']:.8g}")
        elif t == "Ogden":
            n = sum(1 for i in (1, 2, 3) if f"c{i}" in p)
            L.append(f"*HYPERELASTIC, OGDEN, N={n}")
            vals = []
            for i in range(1, n + 1):
                vals += [p[f"c{i}"] / 2.0, p[f"m{i}"]]
            vals += [2.0 / p["k"]] + [0.0] * (n - 1)
            L.append(", ".join(f"{v:.8g}" for v in vals))
        elif t == "Mooney-Rivlin":
            L.append("*HYPERELASTIC, MOONEY-RIVLIN")
            L.append(f"{p['c1']:.8g}, {p['c2']:.8g}, {2.0 / p['k']:.8g}")
        elif t == "neo-Hookean":
            mu = p["E"] / (2 * (1 + p["v"])); K = p["E"] / (3 * (1 - 2 * p["v"]))
            L.append("*HYPERELASTIC, NEO HOOKE")
            L.append(f"{mu / 2:.8g}, {2.0 / K:.8g}")
        else:
            raise ValueError(f"no ABAQUS mapping for {t}")
    # surfaces (element-face based sets are not generated: contact surfaces are written as node-based
    # surfaces is NOT equivalent; we therefore emit surface element sets via *SURFACE, TYPE=ELEMENT only
    # for solid faces identified from the owning element)
    L.append("** Contact pairs, rigid connectors and cable loads must be reviewed before execution.")
    for c in spec.contacts:
        L.append(f"** contact {c['name']}: {c['primary']} <-> {c['secondary']}, friction {c['params'].get('fric_coeff', 0)}")
    L.append("*BOUNDARY")
    for bc in spec.bcs:
        for k, dof in enumerate("xyz", start=1):
            if dof in bc["dofs"]:
                L.append(f"{bc['node_set']}, {k}, {k}")
    for r in spec.rigid_bcs:
        if r["type"] == "rigid_fixed" and r["rb"] in rigid_refs:
            for d in r["dofs"]:
                k = {"Rx": 1, "Ry": 2, "Rz": 3, "Ru": 4, "Rv": 5, "Rw": 6}[d]
                L.append(f"RP_{r['rb']}, {k}, {k}")
    L.append("*STEP, NLGEOM=YES, INC=1000\n*STATIC\n0.05, 1.0, 1e-6, 0.25")
    L.append("*CLOAD")
    for r in spec.rigid_loads:
        if r["rb"] in rigid_refs:
            k = {"Rx": 1, "Ry": 2, "Rz": 3, "Ru": 4, "Rv": 5, "Rw": 6}[r["dof"]]
            L.append(f"RP_{r['rb']}, {k}, {r['value']:.8g}")
    L.append("*OUTPUT, FIELD, VARIABLE=PRESELECT\n*END STEP")
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")
    return {"path": path, "status": "UNEXECUTED", "note": "Contact definitions are listed as comments and must be completed/reviewed."}


def abaqus_available() -> str | None:
    return shutil.which("abaqus")


def run_abaqus(inp: str, workdir: str) -> dict:
    exe = abaqus_available()
    if not exe:
        return {"status": "not run", "reason": "no licensed 'abaqus' command on PATH"}
    job = os.path.splitext(os.path.basename(inp))[0]
    p = subprocess.run([exe, f"job={job}", "interactive"], cwd=workdir, capture_output=True, text=True, stdin=subprocess.DEVNULL)
    sta = os.path.join(workdir, f"{job}.sta")
    ok = os.path.exists(sta) and "COMPLETED SUCCESSFULLY" in open(sta).read()
    return {"status": "converged" if ok else "failed", "returncode": p.returncode}
